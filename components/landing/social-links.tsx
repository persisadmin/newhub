export async function SocialLinks() {
  const { socials } = await getLandingSettings();
  const items = [
    { key: "facebook", href: socials?.facebook, label: "Facebook", Icon: FacebookIcon },
    { key: "youtube", href: socials?.youtube, label: "YouTube", Icon: YoutubeIcon },
    { key: "tiktok", href: socials?.tiktok, label: "TikTok", Icon: TiktokIcon },
    { key: "instagram", href: socials?.instagram, label: "Instagram", Icon: InstagramIcon },
  ].filter((i) => i.href);

  if (items.length === 0) return null;

  return (
    <div className="flex items-center gap-4">
      {items.map(({ key, href, label, Icon }) => (
        <a
          key={key}
          href={href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label}
          title={label}
          className="text-muted-foreground transition-colors hover:text-foreground"
        >
          <Icon size={18} />
        </a>
      ))}
    </div>
  );
}
